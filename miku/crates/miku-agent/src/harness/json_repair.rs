use serde_json::Value;

pub const MAX_REPAIR_INPUT_BYTES: usize = 65_536;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ToolJsonRepairError {
    InputTooLarge { size: usize, max: usize },
    EmptyInput,
    Irreparable(String),
}

impl std::fmt::Display for ToolJsonRepairError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ToolJsonRepairError::InputTooLarge { size, max } => {
                write!(f, "tool json input size {} bytes exceeds max {}", size, max)
            }
            ToolJsonRepairError::EmptyInput => write!(f, "empty tool arguments json"),
            ToolJsonRepairError::Irreparable(msg) => write!(f, "irreparable tool json: {}", msg),
        }
    }
}

impl std::error::Error for ToolJsonRepairError {}

/// Strips markdown code fences (```json ... ``` or ``` ... ```) from raw model output.
fn strip_markdown_fences(input: &str) -> &str {
    let trimmed = input.trim();
    if let Some(rest) = trimmed.strip_prefix("```json") {
        let without_prefix = rest.trim_start();
        if let Some(end_idx) = without_prefix.rfind("```") {
            return without_prefix[..end_idx].trim();
        }
        return without_prefix;
    }
    if let Some(rest) = trimmed.strip_prefix("```") {
        let without_prefix = rest.trim_start();
        if let Some(end_idx) = without_prefix.rfind("```") {
            return without_prefix[..end_idx].trim();
        }
        return without_prefix;
    }
    trimmed
}

/// Attempts to repair malformed JSON payloads commonly generated by LLMs:
/// 1. Strips markdown fences and surrounding commentary.
/// 2. Extracts outermost JSON structure (`{...}` or `[...]`).
/// 3. Closes truncated/missing braces (`}`) and brackets (`]`).
/// 4. Eliminates trailing commas before closing braces/brackets.
/// 5. Normalizes single-quoted keys and strings to standard double quotes.
/// 6. Quotes unquoted identifier keys (`{target: "..."}` -> `{"target": "..."}`).
///
/// Guaranteed to fail closed if input is irreparable, with zero panics and bounded execution.
pub fn repair_tool_call_json(raw: &str) -> Result<Value, ToolJsonRepairError> {
    if raw.len() > MAX_REPAIR_INPUT_BYTES {
        return Err(ToolJsonRepairError::InputTooLarge {
            size: raw.len(),
            max: MAX_REPAIR_INPUT_BYTES,
        });
    }

    let cleaned = strip_markdown_fences(raw);
    if cleaned.is_empty() {
        return Err(ToolJsonRepairError::EmptyInput);
    }

    // Fast path: already valid JSON
    if let Ok(val) = serde_json::from_str::<Value>(cleaned) {
        return Ok(val);
    }

    // Pass 1: Find first '{' or '['
    let start_idx = match cleaned.find(['{', '[']) {
        Some(idx) => idx,
        None => {
            return Err(ToolJsonRepairError::Irreparable(
                "no opening '{' or '[' found in tool arguments".to_string(),
            ));
        }
    };

    let slice = &cleaned[start_idx..];

    // Pass 2: Check balance of braces and quotes
    let mut working = String::with_capacity(slice.len() + 32);
    let mut in_string = false;
    let mut escape_next = false;
    let mut string_quote_char = '"';
    let mut open_brackets: Vec<char> = Vec::new();

    for ch in slice.chars() {
        if in_string {
            if escape_next {
                escape_next = false;
                working.push(ch);
            } else if ch == '\\' {
                escape_next = true;
                working.push(ch);
            } else if ch == string_quote_char {
                in_string = false;
                working.push('"'); // Normalize to double quote
            } else {
                working.push(ch);
            }
        } else {
            match ch {
                '"' | '\'' => {
                    in_string = true;
                    string_quote_char = ch;
                    working.push('"');
                }
                '{' => {
                    open_brackets.push('}');
                    working.push('{');
                }
                '[' => {
                    open_brackets.push(']');
                    working.push('[');
                }
                '}' => {
                    if open_brackets.last() == Some(&'}') {
                        open_brackets.pop();
                        working.push('}');
                    } else if let Some(pos) = open_brackets.iter().rposition(|&c| c == '}') {
                        open_brackets.remove(pos);
                        working.push('}');
                    }
                }
                ']' => {
                    if open_brackets.last() == Some(&']') {
                        open_brackets.pop();
                        working.push(']');
                    } else if let Some(pos) = open_brackets.iter().rposition(|&c| c == ']') {
                        open_brackets.remove(pos);
                        working.push(']');
                    }
                }
                _ => working.push(ch),
            }
        }
    }

    // If string was truncated open, close quote
    if in_string {
        working.push('"');
    }

    // Close any unclosed braces/brackets in reverse order
    while let Some(closing) = open_brackets.pop() {
        working.push(closing);
    }

    // Pass 3: Remove trailing commas before '}' or ']'
    let sanitized_commas = remove_trailing_commas(&working);

    if let Ok(val) = serde_json::from_str::<Value>(&sanitized_commas) {
        return Ok(val);
    }

    // Pass 4: Fix unquoted object keys (e.g. `{target: "val"}` -> `{"target": "val"}`)
    let fixed_keys = quote_unquoted_keys(&sanitized_commas);
    if let Ok(val) = serde_json::from_str::<Value>(&fixed_keys) {
        return Ok(val);
    }

    Err(ToolJsonRepairError::Irreparable(
        "payload remains structurally malformed after all repair passes".to_string(),
    ))
}

fn remove_trailing_commas(input: &str) -> String {
    let mut out = String::with_capacity(input.len());
    let chars: Vec<char> = input.chars().collect();
    let len = chars.len();
    let mut in_str = false;
    let mut escape = false;

    for i in 0..len {
        let ch = chars[i];
        if in_str {
            if escape {
                escape = false;
            } else if ch == '\\' {
                escape = true;
            } else if ch == '"' {
                in_str = false;
            }
            out.push(ch);
        } else if ch == '"' {
            in_str = true;
            out.push(ch);
        } else if ch == ',' {
            // Check if next non-whitespace char is '}' or ']'
            let mut j = i + 1;
            let mut is_trailing = false;
            while j < len {
                let next = chars[j];
                if next == '}' || next == ']' {
                    is_trailing = true;
                    break;
                }
                if !next.is_whitespace() {
                    break;
                }
                j += 1;
            }
            if !is_trailing {
                out.push(',');
            }
        } else {
            out.push(ch);
        }
    }

    out
}

fn quote_unquoted_keys(input: &str) -> String {
    let mut out = String::with_capacity(input.len() + 16);
    let chars: Vec<char> = input.chars().collect();
    let len = chars.len();
    let mut in_str = false;
    let mut escape = false;
    let mut i = 0;

    while i < len {
        let ch = chars[i];
        if in_str {
            if escape {
                escape = false;
            } else if ch == '\\' {
                escape = true;
            } else if ch == '"' {
                in_str = false;
            }
            out.push(ch);
            i += 1;
        } else if ch == '"' {
            in_str = true;
            out.push(ch);
            i += 1;
        } else if ch == '{' || ch == ',' {
            out.push(ch);
            i += 1;
            // Skip whitespace
            while i < len && chars[i].is_whitespace() {
                out.push(chars[i]);
                i += 1;
            }
            // Check if there is an unquoted key (alphanumeric or underscore followed by whitespace or ':')
            if i < len && (chars[i].is_ascii_alphabetic() || chars[i] == '_') {
                let key_start = i;
                while i < len && (chars[i].is_ascii_alphanumeric() || chars[i] == '_' || chars[i] == '-') {
                    i += 1;
                }
                let key: String = chars[key_start..i].iter().collect();
                // Skip whitespace after key
                let mut peek = i;
                while peek < len && chars[peek].is_whitespace() {
                    peek += 1;
                }
                if peek < len && chars[peek] == ':' {
                    out.push('"');
                    out.push_str(&key);
                    out.push('"');
                } else {
                    out.push_str(&key);
                }
            }
        } else {
            out.push(ch);
            i += 1;
        }
    }

    out
}
